// Copies the custom-pairs ABIs and the inspector probe bytecode from Foundry
// output into lib/custom-pairs-artifacts.ts. `--check` fails if the committed
// file no longer matches the Solidity sources (the CBOR metadata tail of the
// probe bytecode is ignored, since it only hashes file metadata).
import { readFileSync, writeFileSync } from "node:fs";

const out = "contracts-custom-pairs/out";
const destination = "lib/custom-pairs-artifacts.ts";
const artifact = (file, name) => JSON.parse(readFileSync(`${out}/${file}/${name}.json`, "utf8"));

const factory = artifact("FortuneCustomPairFactory.sol", "FortuneCustomPairFactory");
const curve = artifact("FortuneCustomPairCurve.sol", "FortuneCustomPairCurve");
const token = artifact("FortuneCustomPairToken.sol", "FortuneCustomPairToken");
const probe = artifact("FortunePairTokenProbe.sol", "FortunePairTokenProbe");

const keep = (abi) => abi.filter((item) => item.type === "function" || item.type === "event" || item.type === "error");
const body = `// Generated by scripts/export-custom-pair-artifacts.mjs from contracts-custom-pairs. Do not edit.

export const CUSTOM_PAIR_FACTORY_ABI = ${JSON.stringify(keep(factory.abi))} as const;

export const CUSTOM_PAIR_CURVE_ABI = ${JSON.stringify(keep(curve.abi))} as const;

export const CUSTOM_PAIR_TOKEN_ABI = ${JSON.stringify(keep(token.abi))} as const;

export const PAIR_TOKEN_PROBE_ABI = ${JSON.stringify(keep(probe.abi))} as const;

/** Runtime code the inspector places at simulated addresses with eth_call state overrides. */
export const PAIR_TOKEN_PROBE_RUNTIME = "${probe.deployedBytecode.object}" as const;
`;

function withoutMetadata(source) {
  return source.replace(/"0x[0-9a-f]+"/gi, (hex) => {
    const raw = hex.slice(3, -1);
    if (raw.length < 4) return hex;
    const tail = parseInt(raw.slice(-4), 16);
    const cut = (tail + 2) * 2;
    return cut > 0 && cut < raw.length ? `"0x${raw.slice(0, -cut)}"` : hex;
  });
}

if (process.argv.includes("--check")) {
  const committed = readFileSync(destination, "utf8");
  if (withoutMetadata(committed) !== withoutMetadata(body)) {
    console.error(`${destination} is out of date. Run: node scripts/export-custom-pair-artifacts.mjs`);
    process.exit(1);
  }
  console.log(`${destination} matches contracts-custom-pairs.`);
} else {
  writeFileSync(destination, body);
  console.log(`Wrote ${destination}`);
}
