// Copies the Stock Rewards ABIs from Foundry output into lib/stock-rewards-artifacts.ts.
// `--check` fails if the committed file no longer matches the Solidity sources.
import { readFileSync, writeFileSync } from "node:fs";

const out = "contracts-stock-rewards/out";
const destination = "lib/stock-rewards-artifacts.ts";
const artifact = (file, name) => JSON.parse(readFileSync(`${out}/${file}/${name}.json`, "utf8"));
const keep = (abi) => abi.filter((item) => item.type === "function" || item.type === "event" || item.type === "error");

const sources = [
  ["STOCK_REWARDS_FACTORY_ABI", "FortuneStockRewardsFactory.sol", "FortuneStockRewardsFactory"],
  ["STOCK_REWARDS_TOKEN_ABI", "FortuneStockRewardsToken.sol", "FortuneStockRewardsToken"],
  // The unchanged Standard contracts every Stock Rewards launch is built from.
  ["STOCK_REWARDS_CURVE_ABI", "FortuneCurve.sol", "FortuneCurve"],
  ["STOCK_REWARDS_FEE_ROUTER_ABI", "FortuneFeeRouter.sol", "FortuneFeeRouter"],
  ["STOCK_REWARDS_REGISTRY_ABI", "FortuneAssetRegistry.sol", "FortuneAssetRegistry"],
  ["STOCK_REWARDS_LOCKER_ABI", "FortunePermanentLiquidityLocker.sol", "FortunePermanentLiquidityLocker"],
  // BSC Testnet only.
  ["TEST_STOCK_ABI", "FortuneTestStock.sol", "FortuneTestStock"],
  ["TEST_STOCK_ORACLE_ABI", "FortuneTestStockOracle.sol", "FortuneTestStockOracle"],
];

const body = `// Generated by scripts/export-stock-rewards-artifacts.mjs from contracts-stock-rewards. Do not edit.
${sources
  .map(([constant, file, name]) => `\nexport const ${constant} = ${JSON.stringify(keep(artifact(file, name).abi))} as const;\n`)
  .join("")}`;

if (process.argv.includes("--check")) {
  const committed = readFileSync(destination, "utf8");
  if (committed !== body) {
    console.error(`${destination} is out of date. Run: node scripts/export-stock-rewards-artifacts.mjs`);
    process.exit(1);
  }
  console.log(`${destination} matches contracts-stock-rewards.`);
} else {
  writeFileSync(destination, body);
  console.log(`Wrote ${destination}`);
}
